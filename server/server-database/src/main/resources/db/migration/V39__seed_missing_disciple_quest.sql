--   ❌ KHÔNG một chữ về hang luyện công, dấu vết hút tu vi, hay cái tên Huyết Sa — cả ba là nhịp
--      TWIST của arc, và §8 quy tắc 2 cấm nói trước, kể cả úp mở.
